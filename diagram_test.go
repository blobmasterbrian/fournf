// TestCardinality
// ---------------------------------------------------------------------------

func TestCardinality(t *testing.T) {
	j := &gen.Type{
		Name: "UserSession",
		Indexes: []*gen.Index{
			{Columns: []string{"user_id"}},
			{Columns: []string{"session_id"}, Unique: true},
			{Columns: []string{"user_id", "session_id"}, Unique: true},
		},
	}
	tests := []struct{ name, fk, want string }{
		{"unique single column", "session_id", "1"},
		{"non-unique single column", "user_id", "0..*"},
		{"absent", "other_id", "0..*"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := cardinality(j, tt.fk); got != tt.want {
				t.Fatalf("cardinality(%q) = %q, want %q", tt.fk, got, tt.want)
			}
		})
	}
}

// ---------------------------------------------------------------------------
// TestFieldType
// ---------------------------------------------------------------------------

func TestFieldType(t *testing.T) {
	// A composite type would introduce a comma, which Mermaid reads as an
	// attribute separator.
	tests := []struct{ in, want string }{
		{"uuid.UUID", "uuid.UUID"},
		{"time.Time", "time.Time"},
		{"map[string]int", "map[string]int"},
		{"func(int, int)", "func(int"},
	}
	for _, tt := range tests {
		t.Run(tt.in, func(t *testing.T) {
			f := &gen.Field{Type: &field.TypeInfo{Ident: tt.in}}
			if got := fieldType(f); got != tt.want {
				t.Fatalf("fieldType(%q) = %q, want %q", tt.in, got, tt.want)
			}
		})
	}
}
